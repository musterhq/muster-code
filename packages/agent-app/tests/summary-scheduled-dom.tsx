assert.equal(rows.length,2);
assert.match(rows[0]!,/Nightly tests.*Next /);
assert.match(rows[1]!,/Paused sweep.*Paused/);
assert.doesNotMatch(section!.textContent!,/Elsewhere/);
(section!.querySelector('.summary-row') as HTMLButtonElement).click();await delay(20);
assert.equal(store.getState().screen,'automations','a row opens Automations');
