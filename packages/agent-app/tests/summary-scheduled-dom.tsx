const React=await import('react');
const {createRoot}=await import('react-dom/client');
const store=await import('../src/renderer/store');
const {SummaryScheduled}=await import('../src/renderer/components/SummaryScheduled');
const errors:unknown[]=[];
const root=createRoot(document.getElementById('root')!,{onUncaughtError:error=>errors.push(error)});
root.render(<SummaryScheduled folderIds={['f1']}/>);await delay(50);
