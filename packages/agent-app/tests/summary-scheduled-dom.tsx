import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {setTimeout as delay} from 'node:timers/promises';
const require=createRequire(import.meta.url);
const {parseHTML}=require('linkedom');
const {window}=parseHTML('<html><body><div id="root"></div></body></html>');
Object.assign(globalThis,{window,document:window.document,HTMLElement:window.HTMLElement,Element:window.Element,localStorage:{getItem(){return null},setItem(){}},requestAnimationFrame:(cb:any)=>setTimeout(cb,0),cancelAnimationFrame:clearTimeout});
(window.HTMLElement.prototype as any).attachEvent=function(){};(window.HTMLElement.prototype as any).detachEvent=function(){};
const calls:string[]=[];
const automation=(id:string,patch:any)=>({id,name:id,prompt:'p',target:{kind:'new',mode:'agent'},schedule:{kind:'interval',minutes:60},timezone:'UTC',permissionMode:'workspace',overlap:'skip',catchUp:'one',paused:false,createdAt:'',updatedAt:'',version:1,summary:'Every hour',issues:[],...patch});
const list=[automation('Nightly tests',{target:{kind:'new',folderId:'f1',mode:'agent'},nextRunAt:new Date(Date.now()+3600_000).toISOString()}),automation('Elsewhere',{target:{kind:'new',folderId:'f2',mode:'agent'}}),automation('Paused sweep',{target:{kind:'new',folderId:'f1',mode:'agent'},paused:true})];
